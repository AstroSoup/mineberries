);

CREATE TABLE incident (
    incident_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT      REFERENCES delivery_order (order_id),
    resolved_by BIGINT      REFERENCES app_user (user_id),
    type        VARCHAR(30) NOT NULL,
    severity    VARCHAR(10) NOT NULL,
    details     TEXT,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP,
    CONSTRAINT ck_incident_type     CHECK (type IN ('DISCREPANCY', 'INVALID_ORDER_STATE', 'SYNC_ERROR',
                                                    'COURIER_DEATH', 'PAYMENT_ERROR')),
    CONSTRAINT ck_incident_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_incident_resolved CHECK (resolved_by IS NULL OR resolved_at IS NOT NULL)
);

CREATE TABLE admin_notification (
