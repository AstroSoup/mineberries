    status      VARCHAR(20)    NOT NULL DEFAULT 'FROZEN',
    frozen_at   TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_at TIMESTAMP,                      -- момент окончательного расчёта (выплата либо возврат)
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_status CHECK (status IN ('FROZEN', 'RELEASED', 'REFUNDED')),
    CONSTRAINT ck_payment_final  CHECK ((status = 'FROZEN') = (released_at IS NULL))
);

CREATE TABLE payment_transaction (
    tx_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id      BIGINT      NOT NULL REFERENCES payment (payment_id),
    type            VARCHAR(30) NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL UNIQUE,
    created_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
