CREATE TABLE dispute (
    dispute_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT      NOT NULL REFERENCES delivery_order (order_id),
    opener_id   BIGINT      NOT NULL REFERENCES app_user (user_id),
    admin_id    BIGINT      REFERENCES app_user (user_id),
    type        VARCHAR(20) NOT NULL,
    description TEXT        NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    resolution  TEXT,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at   TIMESTAMP,
    CONSTRAINT ck_dispute_type   CHECK (type   IN ('LOST', 'DAMAGED')),
    CONSTRAINT ck_dispute_status CHECK (status IN ('OPEN', 'IN_REVIEW', 'RESOLVED', 'REJECTED')),
    CONSTRAINT ck_dispute_closed CHECK ((status IN ('RESOLVED', 'REJECTED')) = (closed_at IS NOT NULL)),
    CONSTRAINT ck_dispute_admin  CHECK (status = 'OPEN' OR admin_id IS NOT NULL)
);
CREATE UNIQUE INDEX uq_dispute_open ON dispute (order_id, opener_id) WHERE status IN ('OPEN', 'IN_REVIEW');

CREATE TABLE dispute_attachment (
    attachment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispute_id    BIGINT       NOT NULL REFERENCES dispute (dispute_id) ON DELETE CASCADE,
    file_key      VARCHAR(255) NOT NULL,
    mime_type     VARCHAR(50)  NOT NULL,
