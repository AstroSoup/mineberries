CREATE TABLE payment (
    payment_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT         NOT NULL UNIQUE REFERENCES delivery_order (order_id),   -- один платёж на заказ
    payer_id    BIGINT         NOT NULL REFERENCES app_user (user_id),
