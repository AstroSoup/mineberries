--changeset mineberries:001-users-module
CREATE TABLE app_user (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname      VARCHAR(16)  NOT NULL,
    password_hash VARCHAR(64) NOT NULL,
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    avatar_key    VARCHAR(255),
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at    TIMESTAMP,
    CONSTRAINT ck_user_nickname CHECK (nickname ~ '^[A-Za-z0-9_]{3,16}$'),
    CONSTRAINT ck_user_status   CHECK (status IN ('ACTIVE', 'BLOCKED', 'DELETED')),
    CONSTRAINT ck_user_deleted  CHECK ((status = 'DELETED') = (deleted_at IS NOT NULL))
);
CREATE UNIQUE INDEX uq_user_nickname_active ON app_user (lower(nickname)) WHERE deleted_at IS NULL;

CREATE TABLE role (
    role_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE permission (
    permission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(100) NOT NULL UNIQUE,
    description   TEXT
);

CREATE TABLE user_role (
    user_id     BIGINT    NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    role_id     BIGINT    NOT NULL REFERENCES role (role_id)     ON DELETE CASCADE,
    assigned_by BIGINT    REFERENCES app_user (user_id),
    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE role_permission (
    role_id       BIGINT NOT NULL REFERENCES role (role_id)             ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permission (permission_id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE user_block (
    block_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT    NOT NULL REFERENCES app_user (user_id),
    admin_id   BIGINT    NOT NULL REFERENCES app_user (user_id),
    reason     TEXT      NOT NULL,
    blocked_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lifted_at  TIMESTAMP,
    CONSTRAINT ck_block_not_self  CHECK (user_id <> admin_id),
    CONSTRAINT ck_block_period    CHECK (lifted_at IS NULL OR lifted_at >= blocked_at)
);
CREATE UNIQUE INDEX uq_user_block_active ON user_block (user_id) WHERE lifted_at IS NULL;

CREATE TABLE notification (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    type            VARCHAR(30) NOT NULL,
    text            TEXT        NOT NULL,
    is_read         BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_notification_type CHECK (type IN ('ORDER', 'PAYMENT', 'DISPUTE', 'COMPENSATION', 'SYSTEM'))
);
--rollback DROP TABLE notification, user_block, role_permission, user_role, permission, role, app_user CASCADE;


--changeset mineberries:002-auth-module
CREATE TABLE session (
    session_id  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id     BIGINT       NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    token_hash  VARCHAR(128) NOT NULL,
    ip_address  VARCHAR(45),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at  TIMESTAMP    NOT NULL,
    revoked_at  TIMESTAMP,
    CONSTRAINT ck_session_period CHECK (expires_at > created_at)
);

CREATE TABLE confirmation_code (
    code_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       REFERENCES app_user (user_id) ON DELETE CASCADE,
    nickname    VARCHAR(16)  NOT NULL,
    action_type VARCHAR(30)  NOT NULL,
    code_hash   VARCHAR(128) NOT NULL,
    attempts    INT          NOT NULL DEFAULT 0,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at  TIMESTAMP    NOT NULL,
    used_at     TIMESTAMP,
    CONSTRAINT ck_code_action   CHECK (action_type IN ('LOGIN', 'REGISTER', 'UPDATE_ACCOUNT', 'DELETE_ACCOUNT')),
    CONSTRAINT ck_code_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_code_period   CHECK (expires_at > created_at),
    CONSTRAINT ck_code_user     CHECK (action_type = 'REGISTER' OR user_id IS NOT NULL),
    CONSTRAINT ck_code_nickname CHECK (nickname ~ '^[A-Za-z0-9_]{3,16}$')
);
--rollback DROP TABLE confirmation_code, session CASCADE;


--changeset mineberries:003-points-catalog-warehouse
CREATE TABLE point (
    point_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    world    VARCHAR(50)  NOT NULL,
    x        INT          NOT NULL,
    y        INT          NOT NULL,
    z        INT          NOT NULL,
    label    VARCHAR(100),
    CONSTRAINT ck_point_y   CHECK (y BETWEEN -64 AND 320),
    CONSTRAINT uq_point_xyz UNIQUE (world, x, y, z)
);

CREATE TABLE category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT       REFERENCES category (category_id),
    name        VARCHAR(100) NOT NULL,
    CONSTRAINT ck_category_not_self CHECK (parent_id IS NULL OR parent_id <> category_id)
);
CREATE UNIQUE INDEX uq_category_name ON category (COALESCE(parent_id, 0), lower(name));

CREATE TABLE item (
    item_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id   BIGINT         NOT NULL REFERENCES category (category_id),
    name          VARCHAR(100)   NOT NULL,
    mc_material   VARCHAR(100)   NOT NULL,
    sell_price    NUMERIC(12, 2) NOT NULL,
    buyout_price  NUMERIC(12, 2) NOT NULL,
    image_key     VARCHAR(255),
    is_active     BOOLEAN        NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_item_sell   CHECK (sell_price   >= 0),
    CONSTRAINT ck_item_buyout CHECK (buyout_price >= 0 AND buyout_price <= sell_price)
);

CREATE TABLE warehouse (
    warehouse_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL,
    point_id     BIGINT       NOT NULL UNIQUE REFERENCES point (point_id),
    is_active    BOOLEAN      NOT NULL DEFAULT TRUE,
    capacity     INT          NOT NULL,
    CONSTRAINT ck_warehouse_capacity CHECK (capacity > 0)
);

CREATE TABLE stock_item (
    warehouse_id      BIGINT    NOT NULL REFERENCES warehouse (warehouse_id),
    item_id           BIGINT    NOT NULL REFERENCES item (item_id),
    quantity          INT       NOT NULL DEFAULT 0,
    reserved_quantity INT       NOT NULL DEFAULT 0,
    max_quantity      INT       NOT NULL DEFAULT 1728, -- one chest
    updated_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (warehouse_id, item_id),
    CONSTRAINT ck_stock_qty      CHECK (quantity >= 0 AND quantity <= max_quantity),
    CONSTRAINT ck_stock_reserved CHECK (reserved_quantity >= 0 AND reserved_quantity <= quantity),
    CONSTRAINT ck_stock_max      CHECK (max_quantity > 0)
);

CREATE TABLE inventory_check (
    check_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT      NOT NULL REFERENCES warehouse (warehouse_id),
    status       VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
    started_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at  TIMESTAMP,
    CONSTRAINT ck_inv_status   CHECK (status IN ('RUNNING', 'FINISHED', 'FAILED')),
    CONSTRAINT ck_inv_finished CHECK ((status = 'RUNNING') = (finished_at IS NULL)),
    CONSTRAINT ck_inv_period   CHECK (finished_at IS NULL OR finished_at >= started_at)
);
CREATE UNIQUE INDEX uq_inventory_running ON inventory_check (warehouse_id) WHERE status = 'RUNNING';

CREATE TABLE inventory_discrepancy (
    discrepancy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_id       BIGINT    NOT NULL REFERENCES inventory_check (check_id) ON DELETE CASCADE,
    item_id        BIGINT    NOT NULL REFERENCES item (item_id),
    expected_qty   INT       NOT NULL,
    actual_qty     INT       NOT NULL,
    detected_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_disc_qty  CHECK (expected_qty >= 0 AND actual_qty >= 0 AND expected_qty <> actual_qty),
    CONSTRAINT uq_disc_item UNIQUE (check_id, item_id)
);
--rollback DROP TABLE inventory_discrepancy, inventory_check, stock_item, warehouse, item, category, point CASCADE;


--changeset mineberries:004-bots-module
CREATE TABLE courier (
    courier_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mc_nickname VARCHAR(16) NOT NULL UNIQUE,
    password    VARCHAR(64) NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'OFFLINE',
    created_by  BIGINT      NOT NULL REFERENCES app_user (user_id),
    is_active   BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_courier_nick   CHECK (mc_nickname ~ '^[A-Za-z0-9_]{3,16}$'),
    CONSTRAINT ck_courier_status CHECK (status IN ('IDLE', 'BUSY', 'OFFLINE')),
    CONSTRAINT ck_courier_active CHECK (is_active OR status = 'OFFLINE')
);

CREATE TABLE courier_position (
    position_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    courier_id  BIGINT           NOT NULL REFERENCES courier (courier_id) ON DELETE CASCADE,
    world       VARCHAR(50)      NOT NULL,
    x           DOUBLE PRECISION NOT NULL,
    y           DOUBLE PRECISION NOT NULL,
    z           DOUBLE PRECISION NOT NULL,
    recorded_at TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE game_event (
    event_id     UUID PRIMARY KEY,
    courier_id   BIGINT      REFERENCES courier (courier_id),
    type         VARCHAR(30) NOT NULL,
    payload      TEXT,
    status       VARCHAR(20) NOT NULL,
    received_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMP
);
--rollback DROP TABLE game_event, courier_position, courier CASCADE;


--changeset mineberries:005-delivery-module
CREATE TABLE delivery_order (
    order_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type             VARCHAR(30)    NOT NULL,
    status           VARCHAR(30)    NOT NULL,
    customer_id      BIGINT         NOT NULL REFERENCES app_user (user_id),
    seller_id        BIGINT         REFERENCES app_user (user_id),
    pickup_point_id  BIGINT         NOT NULL REFERENCES point (point_id),
    dropoff_point_id BIGINT         NOT NULL REFERENCES point (point_id),
    total_price      NUMERIC(12, 2) NOT NULL,
    created_at       TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at          TIMESTAMP,
    confirmed_at     TIMESTAMP,
    closed_at        TIMESTAMP,
    CONSTRAINT ck_order_type   CHECK (type IN ('WAREHOUSE_TO_PLAYER', 'PLAYER_TO_WAREHOUSE', 'PLAYER_TO_PLAYER')),
    CONSTRAINT ck_order_status CHECK (status IN ('AWAITING_PAYMENT', 'QUEUED', 'ASSIGNED', 'IN_TRANSIT',
                                                 'WAITING_RECIPIENT', 'DELIVERED', 'CARGO_LOST', 'DISPUTED',
                                                 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_order_shape CHECK (
        (type = 'WAREHOUSE_TO_PLAYER' AND seller_id IS NULL)
     OR (type = 'PLAYER_TO_PLAYER' AND seller_id IS NOT NULL AND seller_id <> customer_id)
     OR (type = 'PLAYER_TO_WAREHOUSE' AND seller_id IS NOT NULL AND seller_id = customer_id)),
    CONSTRAINT ck_order_price  CHECK ((type =  'PLAYER_TO_WAREHOUSE' AND total_price = 0)
                                   OR (type <> 'PLAYER_TO_WAREHOUSE' AND total_price > 0)),
    CONSTRAINT ck_order_points CHECK (pickup_point_id <> dropoff_point_id),
    CONSTRAINT ck_order_closed CHECK ((status IN ('COMPLETED', 'CANCELLED')) = (closed_at IS NOT NULL)),
    CONSTRAINT ck_order_dates  CHECK (closed_at IS NULL OR closed_at >= created_at)
);

CREATE TABLE order_item (
    order_id   BIGINT         NOT NULL REFERENCES delivery_order (order_id),
    item_id    BIGINT         NOT NULL REFERENCES item (item_id),
    quantity   INT            NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (order_id, item_id),
    CONSTRAINT ck_oi_qty   CHECK (quantity > 0),
    CONSTRAINT ck_oi_price CHECK (unit_price >= 0)
);

CREATE TABLE order_status_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT      NOT NULL REFERENCES delivery_order (order_id),
    old_status VARCHAR(30),
    new_status VARCHAR(30) NOT NULL,
    reason     TEXT,
    changed_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE courier_task (
    task_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT      NOT NULL REFERENCES delivery_order (order_id),
    courier_id   BIGINT      NOT NULL REFERENCES courier (courier_id),
    status       VARCHAR(30) NOT NULL DEFAULT 'ASSIGNED',
    assigned_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    accepted_at  TIMESTAMP,
    picked_up_at TIMESTAMP,
    completed_at TIMESTAMP,
    CONSTRAINT ck_task_status CHECK (status IN ('ASSIGNED', 'ACCEPTED', 'PICKED_UP', 'COMPLETED', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_task_done   CHECK ((status IN ('COMPLETED', 'FAILED', 'CANCELLED')) = (completed_at IS NOT NULL)),
    CONSTRAINT ck_task_order  CHECK ((accepted_at  IS NULL OR accepted_at  >= assigned_at)
                                 AND (picked_up_at IS NULL OR picked_up_at >= assigned_at)
                                 AND (completed_at IS NULL OR completed_at >= assigned_at))
);

CREATE UNIQUE INDEX uq_task_active_order   ON courier_task (order_id)   WHERE status IN ('ASSIGNED', 'ACCEPTED', 'PICKED_UP');
CREATE UNIQUE INDEX uq_task_active_courier ON courier_task (courier_id) WHERE status IN ('ASSIGNED', 'ACCEPTED', 'PICKED_UP');

CREATE TABLE cargo_incident (
    incident_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT      NOT NULL REFERENCES delivery_order (order_id),
    task_id       BIGINT      NOT NULL REFERENCES courier_task (task_id),
    game_event_id UUID        REFERENCES game_event (event_id),
    type          VARCHAR(30) NOT NULL,
    status        VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at   TIMESTAMP,
    CONSTRAINT ck_ci_type     CHECK (type   IN ('LOST', 'DAMAGED', 'COURIER_DEATH')),
    CONSTRAINT ck_ci_status   CHECK (status IN ('OPEN', 'RECOVERING', 'RESOLVED')),
    CONSTRAINT ck_ci_resolved CHECK ((status = 'RESOLVED') = (resolved_at IS NOT NULL))
);
--rollback DROP TABLE cargo_incident, courier_task, order_status_history, order_item, delivery_order CASCADE;


